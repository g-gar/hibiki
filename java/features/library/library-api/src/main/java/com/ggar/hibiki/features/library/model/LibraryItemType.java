package com.ggar.hibiki.features.library.model;

/**
 * Supported types of media items in the user's library.
 */
public enum LibraryItemType {
    /**
     * A single track or song.
     */
    SONG,
    /**
     * A musical album.
     */
    ALBUM,
    /**
     * A user-defined playlist.
     */
    PLAYLIST
}
