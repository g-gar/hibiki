package com.ggar.hibiki.features.devices.model;

/**
 * Type of device registered in the system.
 */
public enum DeviceType {
    /**
     * Web browser.
     */
    WEB,
    /**
     * Mobile device (iOS/Android application).
     */
    MOBILE,
    /**
     * Gaming console.
     */
    CONSOLE,
    /**
     * Desktop application.
     */
    DESKTOP,
    /**
     * Unknown device type.
     */
    UNKNOWN
}
